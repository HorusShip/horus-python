"""Resource classes: one method per operation, namespaces mirroring the operationIds.

``accounts.jobs.create`` -> ``client.accounts.jobs.create(id, kind=...)``.
Each top-level namespace becomes ``horus/resources/<name>.py`` holding the sync and
async classes for it and its sub-namespaces.
"""

from __future__ import annotations

import re
import textwrap
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Sequence, Set, Tuple

from .params import ParamTypes
from .spec import OperationInfo, Param, pascal

HEADER = "# Generated by scripts/generate.py from openapi/openapi.json — do not edit.\n"

# Hand-written behaviour mixed into generated namespaces: namespace -> (module, sync, async).
MIXINS: Dict[Tuple[str, ...], Tuple[str, str, str]] = {
    ("jobs",): ("_jobs", "SyncJobsMixin", "AsyncJobsMixin"),
    ("webhooks",): ("_webhooks", "SyncWebhooksMixin", "AsyncWebhooksMixin"),
}


@dataclass
class Namespace:
    path: Tuple[str, ...]
    ops: List[OperationInfo] = field(default_factory=list)
    children: Dict[str, Namespace] = field(default_factory=dict)

    @property
    def class_name(self) -> str:
        return "".join(pascal(p) for p in self.path) + "Resource"

    def walk(self) -> List[Namespace]:
        """Children first (depth-first), then self."""
        out: List[Namespace] = []
        for child in self.children.values():
            out.extend(child.walk())
        return [*out, self]


def build_tree(ops: Sequence[OperationInfo]) -> Dict[str, Namespace]:
    roots: Dict[str, Namespace] = {}
    for op in ops:
        assert op.namespace, f"{op.op_id}: operationId needs a resource segment"
        node = roots.setdefault(op.namespace[0], Namespace((op.namespace[0],)))
        for depth in range(1, len(op.namespace)):
            node = node.children.setdefault(op.namespace[depth], Namespace(op.namespace[: depth + 1]))
        node.ops.append(op)
    for root in roots.values():
        for ns in root.walk():
            _check_names(ns)
    return roots


def _check_names(ns: Namespace) -> None:
    methods = [op.py_method for op in ns.ops]
    clash = set(methods) & set(ns.children)
    assert not clash, f"{'.'.join(ns.path)}: {clash} is both a method and a namespace"
    assert len(methods) == len(set(methods)), f"{'.'.join(ns.path)}: duplicate methods"


# -- module rendering ------------------------------------------------------------------------
class ModuleRenderer:
    def __init__(self, root: Namespace, param_types: ParamTypes) -> None:
        self.root = root
        self.types = param_types
        self.models: Set[str] = set()
        self.params_used: Set[str] = set()

    def render(self) -> str:
        namespaces = self.root.walk()
        constants = [_operation_constant(op) for ns in namespaces for op in ns.ops]
        sync = [self._class(ns, is_async=False) for ns in namespaces]
        async_ = [self._class(ns, is_async=True) for ns in namespaces]
        return HEADER + self._imports() + "\n\n" + "\n".join(constants) + "\n\n\n" + "\n\n".join([*sync, *async_])

    def _imports(self) -> str:
        lines = [
            "from __future__ import annotations",
            "",
            "import datetime",
            "from typing import TYPE_CHECKING, Mapping, Optional, Sequence, Union",
            "",
            "from typing_extensions import Literal",
            "",
            "from .._operation import Operation",
            "from .._pagination import AsyncPaginator, SyncPage",
            "from .._resource import AsyncAPIResource, SyncAPIResource",
            "from .._types import NOT_GIVEN, NotGiven, RequestOptions",
        ]
        lines += self._mixin_imports()
        if self.models:
            lines.append(f"from ..types import {', '.join(sorted(self.models))}")
        if self.params_used:
            lines.append(f"from ..types.params import {', '.join(sorted(self.params_used))}")
        if any(ns.children for ns in self.root.walk()):
            lines += ["", "if TYPE_CHECKING:", "    from .._base_client import AsyncAPIClient, SyncAPIClient"]
        return "\n".join(lines) + "\n\n__all__ = [" + ", ".join(f'"{n}"' for n in self._exports()) + "]\n"

    def _mixin_imports(self) -> List[str]:
        out = []
        for ns in self.root.walk():
            if ns.path in MIXINS:
                module, sync, async_ = MIXINS[ns.path]
                out.append(f"from .{module} import {async_}, {sync}")
        return out

    def _exports(self) -> List[str]:
        names = [ns.class_name for ns in self.root.walk()]
        return [*names, *("Async" + n for n in names)]

    def _class(self, ns: Namespace, *, is_async: bool) -> str:
        prefix = "Async" if is_async else ""
        bases = ["AsyncAPIResource" if is_async else "SyncAPIResource"]
        if ns.path in MIXINS:
            bases.insert(0, MIXINS[ns.path][2 if is_async else 1])
        doc = f'    """``client.{".".join(ns.path)}``"""\n'
        parts = [f"class {prefix}{ns.class_name}({', '.join(bases)}):\n{doc}"]
        if ns.children:
            parts.append(_init(ns, prefix, is_async))
        parts += [self._method(op, is_async) for op in ns.ops]
        return "\n".join(parts)

    def _method(self, op: OperationInfo, is_async: bool) -> str:
        return MethodRenderer(op, self, is_async).render()

    def note_model(self, name: str) -> str:
        self.models.add(name)
        return name

    def annotation(self, param: Param, hint: str) -> str:
        text = self.types.annotation(param.schema, hint, query=param.location == "query")
        self.params_used.update(n for n in re.findall(r"\b\w+Param\b", text) if n in self.types.defs)
        return text


def _init(ns: Namespace, prefix: str, is_async: bool) -> str:
    client = "AsyncAPIClient" if is_async else "SyncAPIClient"
    lines = [f"    def __init__(self, client: {client}) -> None:", "        super().__init__(client)"]
    for name, child in ns.children.items():
        lines.append(f"        self.{name} = {prefix}{child.class_name}(client)")
    return "\n".join(lines) + "\n"


def _operation_constant(op: OperationInfo) -> str:
    fields = [
        f'id="{op.op_id}"',
        f'method="{op.method}"',
        f'path="{op.path}"',
        f"path_params={_tuple(p.name for p in op.path_params)}",
        f"query_params={_tuple(p.name for p in op.query_params)}",
        f"body_params={_tuple(p.name for p in op.body_params)}",
        f"has_body={op.has_body}",
        f"idempotent={op.idempotent}",
        f"paginated={op.page_item is not None}",
        f"requires_desktop={op.requires_desktop}",
        f"scopes={_tuple(op.scopes)}",
    ]
    return f"{op.const_name} = Operation({', '.join(fields)})"


def _tuple(items: Iterable[str]) -> str:
    values = [f'"{v}"' for v in items]
    return "(" + ", ".join(values) + ("," if len(values) == 1 else "") + ")"


# -- one method ------------------------------------------------------------------------------
class MethodRenderer:
    def __init__(self, op: OperationInfo, module: ModuleRenderer, is_async: bool) -> None:
        self.op = op
        self.module = module
        self.is_async = is_async
        self.hint = pascal(op.op_id.replace(".", "_"))

    def render(self) -> str:
        args = self._args()
        returns = self._returns()
        is_coroutine = self.is_async and self.op.page_item is None
        head = f"    {'async ' if is_coroutine else ''}def {self.op.py_method}(\n" + "".join(
            f"        {a},\n" for a in args
        )
        head += f"    ) -> {returns}:\n"
        return head + self._docstring() + self._body(is_coroutine)

    def _kw_params(self) -> List[Param]:
        params = [*self.op.query_params, *self.op.body_params]
        return sorted(params, key=lambda p: not p.required)

    def _args(self) -> List[str]:
        args = ["self"] + [
            f"{p.py_name}: {self.module.annotation(p, self.hint + pascal(p.name))}" for p in self.op.path_params
        ]
        kw = self._kw_params()
        args.append("*")
        for p in kw:
            ann = self.module.annotation(p, self.hint + pascal(p.name))
            args.append(f"{p.py_name}: {ann}" if p.required else f"{p.py_name}: {_or_not_given(ann)} = NOT_GIVEN")
        if self.op.idempotent:
            args.append("idempotency_key: Optional[str] = None")
        args.append("options: Optional[RequestOptions] = None")
        return args

    def _returns(self) -> str:
        if self.op.page_item:
            item = self.module.note_model(self.op.page_item)
            return f"AsyncPaginator[{item}]" if self.is_async else f"SyncPage[{item}]"
        return self.module.note_model(self.op.response_model)

    def _docstring(self) -> str:
        op = self.op
        lines = [op.summary.rstrip(".") + "." if op.summary else op.op_id]
        if op.description:
            lines += ["", *textwrap.wrap(op.description, 88)]
        lines += ["", f"``{op.method.upper()} {op.path}`` (operation ``{op.op_id}``)."]
        if op.scopes:
            lines.append(f"Scopes: {', '.join(op.scopes)}.")
        if op.requires_desktop:
            lines.append("Runs on your Horus Desktop (503 ``desktop_offline`` when it isn't online).")
        if op.page_item:
            lines.append("Returns the first page; iterate it to walk every item.")
        lines += self._arg_docs()
        text = "\n".join(f"        {line}".rstrip() for line in lines)
        return '        """' + text.strip().replace("\\", "\\\\").replace('"""', "'''") + '\n        """\n'

    def _arg_docs(self) -> List[str]:
        described = [
            p for p in [*self.op.path_params, *self._kw_params()] if p.description and p.description != "Resource id."
        ]
        if not described:
            return []
        out = ["", "Args:"]
        for p in described:
            wrapped = textwrap.wrap(f"{p.py_name}: {p.description}", 84)
            out += ["  " + wrapped[0], *("    " + w for w in wrapped[1:])]
        return out

    def _body(self, is_coroutine: bool) -> str:
        op = self.op
        call = "_call_page" if op.page_item else "_call"
        target = self.module.note_model(op.page_item or op.response_model)
        kwargs = []
        if op.path_params:
            kwargs.append("path={" + ", ".join(f'"{p.name}": {p.py_name}' for p in op.path_params) + "}")
        kw = self._kw_params()
        if kw:
            kwargs.append("params={" + ", ".join(f'"{p.name}": {p.py_name}' for p in kw) + "}")
        if op.idempotent:
            kwargs.append("idempotency_key=idempotency_key")
        kwargs.append("options=options")
        prefix = "await " if is_coroutine else ""
        lines = [
            f"        return {prefix}self._client.{call}(",
            f"            {op.const_name},",
            f"            {target},",
        ]
        lines += [f"            {k}," for k in kwargs]
        return "\n".join(lines) + "\n        )\n"


def _or_not_given(annotation: str) -> str:
    """``X`` -> ``Union[X, NotGiven]``, flattening an outer ``Union[...]``."""
    if annotation.startswith("Union[") and _outer_bracket_closes_at_end(annotation):
        return annotation[:-1] + ", NotGiven]"
    return f"Union[{annotation}, NotGiven]"


def _outer_bracket_closes_at_end(text: str) -> bool:
    depth = 0
    for i, ch in enumerate(text):
        depth += ch == "["
        depth -= ch == "]"
        if depth == 0 and ch == "]":
            return i == len(text) - 1
    return False


def render_module(root: Namespace, param_types: ParamTypes) -> str:
    return ModuleRenderer(root, param_types).render()


def render_package_init(roots: Dict[str, Namespace]) -> str:
    """``resources/__init__.py``: the attribute list of the clients."""
    imports = []
    sync_attrs, async_attrs, sync_init, async_init = [], [], [], []
    for name in sorted(roots):
        cls = roots[name].class_name
        imports.append(f"from .{name} import Async{cls}, {cls}")
        sync_attrs.append(f"    {name}: {cls}")
        async_attrs.append(f"    {name}: Async{cls}")
        sync_init.append(f"        self.{name} = {cls}(client)")
        async_init.append(f"        self.{name} = Async{cls}(client)")
    return (
        HEADER
        + '"""Resource namespaces of :class:`horus.Horus` and :class:`horus.AsyncHorus`."""\n\n'
        + "from __future__ import annotations\n\nfrom typing import TYPE_CHECKING\n\n"
        + "\n".join(imports)
        + "\n\nif TYPE_CHECKING:\n    from .._base_client import AsyncAPIClient, SyncAPIClient\n\n"
        + '__all__ = ["SyncResources", "AsyncResources"]\n\n\n'
        + 'class SyncResources:\n    """Every API namespace (sync)."""\n\n'
        + "\n".join(sync_attrs)
        + "\n\n    def _init_resources(self, client: SyncAPIClient) -> None:\n"
        + "\n".join(sync_init)
        + '\n\n\nclass AsyncResources:\n    """Every API namespace (async)."""\n\n'
        + "\n".join(async_attrs)
        + "\n\n    def _init_resources(self, client: AsyncAPIClient) -> None:\n"
        + "\n".join(async_init)
        + "\n"
    )


def operation_index(ops: Sequence[OperationInfo]) -> str:
    """``resources/_index.py``: operationId -> (attribute path, method), for tooling and tests."""
    rows = [f'    "{op.op_id}": ({_tuple(op.namespace)}, "{op.py_method}"),' for op in ops]
    return (
        HEADER
        + '"""Every operation in the spec and where it lives on the client."""\n\n'
        + "from typing import Dict, Tuple\n\n"
        + "OPERATIONS: Dict[str, Tuple[Tuple[str, ...], str]] = {\n"
        + "\n".join(rows)
        + "\n}\n"
    )
