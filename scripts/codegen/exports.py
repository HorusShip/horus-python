"""``horus/types/__init__.py`` and the webhook event registry."""

from __future__ import annotations

import re
from typing import List, Sequence, Tuple

HEADER = "# Generated by scripts/generate.py from openapi/openapi.json — do not edit.\n"


def model_names(models_source: str) -> List[str]:
    return re.findall(r"^class (\w+)\(", models_source, flags=re.MULTILINE)


def render_types_init(names: Sequence[str]) -> str:
    body = "".join(f"    {n},\n" for n in names)
    exported = "".join(f'    "{n}",\n' for n in [*names, "EVENT_TYPES", "WebhookEvent"])
    return (
        HEADER
        + '"""Typed API objects (pydantic models), generated from the OpenAPI spec."""\n\n'
        + "from ._events import EVENT_TYPES, WebhookEvent\n"
        + f"from ._models import (\n{body})\n\n"
        + f"__all__ = [\n{exported}]\n"
    )


def render_events(events: Sequence[Tuple[str, str]]) -> str:
    """``EVENT_TYPES``: event type -> payload model; ``WebhookEvent``: their union."""
    classes = sorted({cls for _, cls in events})
    rows = "".join(f'    "{name}": {cls},\n' for name, cls in events)
    union = "".join(f"    {cls},\n" for cls in classes)
    imports = "".join(f"    {cls},\n" for cls in ["Event", *classes])
    return (
        HEADER
        + '"""Webhook event types (the spec\'s ``webhooks`` section)."""\n\n'
        + "from typing import Dict, Type, Union\n\n"
        + f"from ._models import (\n{imports})\n\n"
        + '__all__ = ["EVENT_TYPES", "WebhookEvent"]\n\n'
        + f"EVENT_TYPES: Dict[str, Type[Event]] = {{\n{rows}}}\n"
        + '"""Event type (``"sale.shipped"``) -> its payload model."""\n\n'
        + f"WebhookEvent = Union[\n{union}    Event,\n]\n"
        + '"""Any webhook event; unknown (newer) types parse as the base :class:`Event`."""\n'
    )
