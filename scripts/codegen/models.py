"""Response models: pydantic v2 classes generated with ``datamodel-code-generator``.

Inline 2xx response schemas (the ``{id, object, deleted}`` shapes) are lifted into named
components first, so every operation returns a named model.
"""

from __future__ import annotations

import copy
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import List

from .spec import Schema, Spec, ref_name

HEADER = "# Generated by scripts/generate.py from openapi/openapi.json — do not edit.\n"

CODEGEN_ARGS = [
    "--input-file-type", "openapi",
    "--openapi-scopes", "schemas",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.10",
    "--no-use-union-operator",
    "--use-standard-collections",
    "--use-annotated",
    "--field-constraints",
    "--enum-field-as-literal", "all",
    "--use-double-quotes",
    "--naming-strategy", "parent-prefixed",
    "--disable-timestamp",
    "--keep-model-order",
    "--use-schema-description",
    "--use-field-description",
    "--base-class", "horus._models.HorusModel",
    "--formatters", "black", "isort",
]


def lifted_document(spec: Spec) -> Schema:
    """The spec with inline success-response schemas named and moved into components."""
    doc = copy.deepcopy(spec.doc)
    schemas = doc["components"]["schemas"]
    for _path, _method, op in Spec(doc).raw_operations():
        for code, resp in op["responses"].items():
            content = resp.get("content", {}).get("application/json")
            if not code.startswith("2") or not content or ref_name(content["schema"]):
                continue
            name = spec.response_model_name(op["operationId"], content["schema"])
            schemas[name] = content["schema"]
            content["schema"] = {"$ref": f"#/components/schemas/{name}"}
    _lift_event_data(schemas)
    doc.pop("webhooks", None)
    return doc


def _lift_event_data(schemas: Schema) -> None:
    """``SaleShippedEvent.data`` (inline) -> component ``SaleShippedEventData``."""
    for name in [n for n in schemas if n.endswith("Event")]:
        for part in schemas[name].get("allOf", []):
            data = part.get("properties", {}).get("data")
            if isinstance(data, dict) and "properties" in data:
                schemas[f"{name}Data"] = data
                part["properties"]["data"] = {"$ref": f"#/components/schemas/{name}Data"}


def generate_models(spec: Spec, output: Path) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        source = Path(tmp) / "openapi.json"
        source.write_text(json.dumps(lifted_document(spec)), encoding="utf-8")
        target = Path(tmp) / "models.py"
        _run_codegen(source, target)
        output.write_text(HEADER + _postprocess(target.read_text(encoding="utf-8")), encoding="utf-8")


def _run_codegen(source: Path, target: Path) -> None:
    exe = Path(sys.executable).with_name("datamodel-codegen")
    cmd: List[str] = [str(exe), "--input", str(source), "--output", str(target), *CODEGEN_ARGS]
    subprocess.run(cmd, check=True, capture_output=True, text=True)


def _postprocess(code: str) -> str:
    """Drop the tool's own header comment (we write ours)."""
    lines = code.splitlines(keepends=True)
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    return "".join(lines).lstrip("\n")
