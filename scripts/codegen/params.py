"""Input types: JSON Schema -> Python annotations for method arguments.

Primitive fields become plain annotations (``str``, ``Literal[...]``, ``Sequence[int]``);
nested objects become ``TypedDict`` classes in ``horus/types/params.py`` (plain dicts at
runtime, fully checked by mypy/pyright).
"""

from __future__ import annotations

import keyword
from dataclasses import dataclass, field
from typing import Dict, List, Tuple

from .spec import Schema, Spec, pascal, ref_name

HEADER = '''# Generated by scripts/generate.py from openapi/openapi.json — do not edit.
"""Request parameter types (``TypedDict``) for nested request-body objects."""

from __future__ import annotations

import datetime
from typing import Mapping, Optional, Sequence, Union

from typing_extensions import Literal, NotRequired, TypedDict

'''


@dataclass
class TypedDictDef:
    name: str
    fields: List[Tuple[str, str, bool, str]]
    """``(wire name, annotation, required, description)``."""
    doc: str = ""


@dataclass
class ParamTypes:
    """Collects the TypedDicts needed while rendering annotations."""

    spec: Spec
    defs: Dict[str, TypedDictDef] = field(default_factory=dict)

    def annotation(self, schema: Schema, hint: str, *, query: bool = False) -> str:
        """The annotation for ``schema``; ``hint`` names any TypedDict it needs."""
        types = schema.get("type")
        if isinstance(types, list):
            parts = [self.annotation({**schema, "type": t}, hint, query=query) for t in types if t != "null"]
            inner = parts[0] if len(parts) == 1 else f"Union[{', '.join(parts)}]"
            return f"Optional[{inner}]" if "null" in types else inner
        return self._single(schema, hint, query)

    def _single(self, schema: Schema, hint: str, query: bool) -> str:
        ref = ref_name(schema)
        if ref:
            return self._typed_dict(ref + "Param", self.spec.schemas[ref], ref)
        if "anyOf" in schema or "oneOf" in schema:
            members = schema.get("anyOf") or schema.get("oneOf") or []
            options = _dedupe([self.annotation(m, f"{hint}Variant{i}", query=query) for i, m in enumerate(members)])
            return options[0] if len(options) == 1 else f"Union[{', '.join(options)}]"
        if "enum" in schema:
            return self._enum(schema["enum"], query)
        return self._by_type(schema, hint, query)

    def _by_type(self, schema: Schema, hint: str, query: bool) -> str:
        kind = schema.get("type")
        if kind == "string":
            return "Union[str, datetime.datetime]" if schema.get("format") == "date-time" else "str"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"Sequence[{self.annotation(schema.get('items', {}), hint + 'Item', query=query)}]"
        if kind == "object" or "properties" in schema:
            if schema.get("properties"):
                return self._typed_dict(hint + "Param", schema, hint)
            return "Mapping[str, object]"
        return "object"

    @staticmethod
    def _enum(values: List[object], query: bool) -> str:
        if query and sorted(map(str, values)) == ["false", "true"]:
            return 'Union[bool, Literal["true", "false"]]'
        return "Literal[" + ", ".join(_literal(v) for v in values) + "]"

    def _typed_dict(self, name: str, schema: Schema, hint: str) -> str:
        if name in self.defs:
            return name
        definition = TypedDictDef(name=name, fields=[], doc=str(schema.get("description") or ""))
        self.defs[name] = definition  # registered first: recursive schemas terminate
        required = set(schema.get("required", []) or [])
        for prop, sub in schema.get("properties", {}).items():
            annotation = self.annotation(sub, hint + pascal(prop))
            definition.fields.append((prop, annotation, prop in required, str(sub.get("description") or "")))
        return name

    def render_module(self) -> str:
        blocks = [_render_typed_dict(d) for d in sorted(self.defs.values(), key=lambda d: d.name)]
        names = ", ".join(f'"{d}"' for d in sorted(self.defs))
        return HEADER + f"__all__ = [{names}]\n\n\n" + "\n\n".join(blocks)


def _render_typed_dict(d: TypedDictDef) -> str:
    if any(keyword.iskeyword(name) or not name.isidentifier() for name, *_ in d.fields):
        return _render_functional(d)
    lines = [f"class {d.name}(TypedDict):"]
    lines.append(f'    """{_doc(d.doc) or d.name}"""')
    lines.append("")
    for name, annotation, required, description in d.fields:
        lines.append(f"    {name}: {annotation if required else f'NotRequired[{annotation}]'}")
        if description:
            lines.append(f'    """{_doc(description)}"""')
    return "\n".join(lines) + "\n"


def _render_functional(d: TypedDictDef) -> str:
    entries = ", ".join(f'"{n}": {a if r else f"NotRequired[{a}]"}' for n, a, r, _ in d.fields)
    return f'{d.name} = TypedDict("{d.name}", {{{entries}}})\n'


def _doc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', "'''").strip()


def _literal(value: object) -> str:
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return repr(value)


def _dedupe(items: List[str]) -> List[str]:
    seen: List[str] = []
    for item in items:
        if item not in seen:
            seen.append(item)
    return seen
